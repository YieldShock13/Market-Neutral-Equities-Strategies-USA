def estimate_market_betas(prices, tickers):
    """
    Estimate relative market exposure using the
    equal-weighted return of the available stock universe
    as a temporary market proxy.

    This is NOT SPY or an external benchmark.
    A proper benchmark series can replace this function
    when connected to the daily data updater.
    """

    log_returns = np.log(prices).diff().iloc[1:]

    market = log_returns.mean(axis=1).to_numpy(
        dtype=float
    )

    market_var = np.var(market, ddof=1)

    if market_var <= EPS:
        raise ValueError("Market proxy variance is zero")

    betas = []

    for ticker in tickers:
        r = log_returns[ticker].to_numpy(
            dtype=float
        )

        beta = (
            np.cov(r, market, ddof=1)[0, 1]
            / market_var
        )

        betas.append(beta)

    return np.asarray(betas, dtype=float)


def construct_raw_signal(B, Sigma, deviation):
    """
    Mean-reversion direction:

        coordinate_signal = -Sigma^-1 deviation

        stock_signal = B @ coordinate_signal

    Corrects the sign issue discussed in Stage 4.

    These are log-price sensitivity exposures,
    not yet executable stock quantities.
    """

    coordinate_signal = -np.linalg.solve(
        Sigma, deviation
    )

    stock_signal = B @ coordinate_signal

    return stock_signal, coordinate_signal


def neutralize_signal(raw, betas):
    """
    Find the closest vector to the original signal
    satisfying:

        sum(weights) = 0
        dot(weights, betas) = 0

    Uses an orthogonal projection.

    IMPORTANT:
    This is a portfolio-construction overlay.
    The resulting vector need not lie in the original
    Johansen cointegrating subspace.
    """

    n = len(raw)

    constraints = np.vstack([
        np.ones(n),
        betas
    ])

    if np.linalg.matrix_rank(
        constraints, tol=BETA_VARIATION_TOL
    ) < 2:
        raise ValueError(
            "Dollar and beta constraints are dependent"
        )

    gram = constraints @ constraints.T

    projected = (
        raw
        - constraints.T @ np.linalg.solve(
            gram,
            constraints @ raw
        )
    )

    gross = np.sum(np.abs(projected))

    if gross <= EPS:
        raise ValueError(
            "Neutralization eliminated the signal"
        )

    weights = projected / gross

    return weights


