import yfinance as yf
import pandas as pd
import numpy as np

TICKERS = ["MSFT", "AAPL", "JPM", "O", "F"]
START = "2024-01-01"
END = (pd.Timestamp.now(tz="UTC") + pd.Timedelta(days=1)).strftime("%Y-%m-%d")

results = []
daily_data = {}

for symbol in TICKERS:
    print(f"\nTesting {symbol}")

    try:
        stock = yf.Ticker(symbol)

        prices = stock.history(
            start=START,
            end=END,
            interval="1d",
            auto_adjust=False,
            actions=True
        )

        shares = stock.get_shares_full(
            start=START,
            end=END
        )

        if prices.empty:
            raise ValueError("No price history returned")

        prices.index = pd.to_datetime(prices.index).tz_localize(None)
        prices.index = prices.index.normalize()

        df = prices[["Close", "Adj Close"]].copy()

        share_observations = 0
        conflicting_dates = 0

        if shares is not None and len(shares):
            s = shares.copy()
            s.index = pd.to_datetime(s.index).tz_localize(None)
            s.index = s.index.normalize()
            s = pd.to_numeric(s, errors="coerce")
            s = s[s.gt(0)].sort_index()

            share_observations = len(s)
            conflicting_dates = int(
                s.groupby(level=0).nunique().gt(1).sum()
            )

            # Conflicting dates are excluded, not silently resolved.
            conflicting = s.groupby(level=0).nunique()
            bad_dates = conflicting[conflicting.gt(1)].index
            s = s[~s.index.isin(bad_dates)]
            s = s[~s.index.duplicated(keep="last")]

            # Forward-fill only from an observed historical share count.
            df["Shares"] = s.reindex(
                df.index.union(s.index)
            ).sort_index().ffill().reindex(df.index)
        else:
            df["Shares"] = np.nan

        df["MarketCap"] = df["Close"] * df["Shares"]
        df["Eligible_2bn"] = df["MarketCap"] >= 2e9

        # Missing share data means UNKNOWN, not ineligible.
        df.loc[df["MarketCap"].isna(), "Eligible_2bn"] = pd.NA
        df["Eligible_2bn"] = df["Eligible_2bn"].astype("boolean")

        coverage = df["MarketCap"].notna().mean()

        results.append({
            "Ticker": symbol,
            "PriceDays": len(df),
            "ShareObservations": share_observations,
            "ConflictingShareDates": conflicting_dates,
            "MarketCapCoverage": round(coverage * 100, 2),
            "LatestMarketCapUSD": df["MarketCap"].iloc[-1],
            "LatestEligible": df["Eligible_2bn"].iloc[-1]
        })

        daily_data[symbol] = df

    except Exception as e:
        print(f"FAILED: {type(e).__name__}: {e}")
        results.append({
            "Ticker": symbol,
            "Error": str(e)
        })

audit = pd.DataFrame(results)
display(audit)

