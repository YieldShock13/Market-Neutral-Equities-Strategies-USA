def market_betas(prices, tickers):
    returns = np.log(prices).diff().iloc[1:]
    market = returns.mean(axis=1).to_numpy()
    variance = np.var(market, ddof=1)

    if not np.isfinite(variance) or variance <= 0:
        raise ValueError("Invalid market proxy variance")

    betas = []
    for ticker in tickers:
        r = returns[ticker].to_numpy()
        betas.append(
            np.cov(r, market, ddof=1)[0, 1] / variance
        )

    return np.asarray(betas, dtype=float)

def constrained_signal(B, Sigma, deviation, betas):
    """
    Raw mean-reversion signal:
        s = -B @ inv(Sigma) @ deviation

    Restrict portfolio weights to:
        w = B @ a

    Subject to:
        sum(w) = 0
        betas @ w = 0

    If no nonzero solution exists, report infeasibility.
    """

    coordinate = -np.linalg.solve(Sigma, deviation)
    raw = B @ coordinate

    # Orthonormal basis for cointegrating subspace.
    U, singular, _ = np.linalg.svd(
        B, full_matrices=False
    )

    rank = int(np.sum(
        singular > singular[0] * 1e-10
    ))

    U = U[:, :rank]

    # Constraints expressed within that subspace.
    C = np.vstack([
        np.ones(len(betas)),
        betas
    ])

    M = C @ U

    # Nullspace of the restricted constraints.
    _, s, Vt = np.linalg.svd(
        M, full_matrices=True
    )

    if len(s):
        matrix_rank = int(np.sum(
            s > max(M.shape) * np.finfo(float).eps * s[0]
        ))
    else:
        matrix_rank = 0

    N = Vt[matrix_rank:].T

    if N.shape[1] == 0:
        return None, raw, "CONSTRAINT_INFEASIBLE", np.nan

    # Orthogonal projection of original signal onto
    # feasible directions within cointegrating subspace.
    feasible_basis = U @ N
    projected = feasible_basis @ (
        feasible_basis.T @ raw
    )

    norm = np.linalg.norm(projected)
    raw_norm = np.linalg.norm(raw)

    if norm <= TOL or raw_norm <= TOL:
        return None, raw, "SIGNAL_ELIMINATED", np.nan

    alignment = float(
        np.dot(raw, projected) / (raw_norm * norm)
    )

    gross = np.sum(np.abs(projected))
    weights = projected / gross

    if (
        abs(np.sum(weights)) > TOL
        or abs(np.dot(weights, betas)) > TOL
    ):
        return None, raw, "NEUTRALITY_FAILED", alignment

    status = (
        "VALIDATED_MATHEMATICAL_SIGNAL"
        if alignment >= ALIGNMENT_MIN
        else "LOW_SIGNAL_ALIGNMENT"
    )

    return weights, raw, status, alignment


