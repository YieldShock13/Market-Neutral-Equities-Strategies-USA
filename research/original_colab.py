def estimate_training_vector(Y):
    """
    Johansen estimation on training observations only.
    Stage 3 baseline specification:
      det_order=0, k_ar_diff=1.
    """
    result = coint_johansen(
        Y, det_order=0, k_ar_diff=1
    )

    trace_rank = int(np.sum(
        result.lr1 > result.cvt[:, 1]
    ))
    maxeig_rank = int(np.sum(
        result.lr2 > result.cvm[:, 1]
    ))

    rank = min(trace_rank, maxeig_rank)

    if rank < 1 or rank >= Y.shape[1]:
        return None

    return result.evec[:, :rank]

def fit_training_mvou(X):
    """
    Fit VAR(1) representation of the spread coordinates.
    """
    x0 = X[:-1]
    x1 = X[1:]

    design = np.column_stack([
        np.ones(len(x0)), x0
    ])

    coefficients = np.linalg.lstsq(
        design, x1, rcond=None
    )[0]

    intercept = coefficients[0]
    A = coefficients[1:].T

    if np.max(np.abs(np.linalg.eigvals(A))) >= 1:
        return None

    residuals = x1 - design @ coefficients
    Q = np.atleast_2d(
        np.cov(residuals, rowvar=False)
    )

    mu = np.linalg.solve(
        np.eye(A.shape[0]) - A, intercept
    )

    Sigma = solve_discrete_lyapunov(A, Q)

    return A, mu, Sigma

def evaluate_basket(prices, tickers):
    Y = np.log(
        prices[tickers].to_numpy(dtype=float)
    )

    n = len(Y)
    split = int(n * TRAIN_FRACTION)

    if n - split < MIN_TEST_OBS:
        raise ValueError("Insufficient test observations")

    Y_train = Y[:split]
    Y_test = Y[split:]

    B = estimate_training_vector(Y_train)

    if B is None:
        return {
            "Status": "TRAIN_COINTEGRATION_FAILED"
        }

    X_train = Y_train @ B
    X_test = Y_test @ B

    fitted = fit_training_mvou(X_train)

    if fitted is None:
        return {
            "Status": "TRAIN_MVOU_UNSTABLE"
        }

    A, mu, Sigma = fitted

    if B.shape[1] != 1:
        return {
            "Status": "MULTIVARIATE_VALIDATION_REQUIRED"
        }

    train_spread = X_train[:, 0]
    test_spread = X_test[:, 0]

    train_mu = float(mu[0])
    train_sigma = float(np.sqrt(Sigma[0, 0]))

    if train_sigma <= EPS:
        raise ValueError("Invalid stationary variance")

    test_z = (
        test_spread - train_mu
    ) / train_sigma

    # Test-set stationarity diagnostic.
    adf_p = float(
        adfuller(
            test_spread,
            regression="c",
            autolag="AIC"
        )[1]
    )

    # Mean-reversion diagnostic: does the absolute
    # standardized deviation contract next session?
    current = np.abs(test_z[:-1])
    following = np.abs(test_z[1:])

    contraction_rate = float(
        np.mean(following < current)
    )

    # Historical equilibrium stability.
    equilibrium_shift = float(
        abs(np.mean(test_spread) - train_mu)
        / train_sigma
    )

    # Dispersion relative to training.
    dispersion_ratio = float(
        np.std(test_spread, ddof=1)
        / train_sigma
    )

    return {
        "Status": "VALIDATION_COMPUTED",
        "TrainObservations": len(Y_train),
        "TestObservations": len(Y_test),
        "TrainCointegrationRank": B.shape[1],
        "TestADFp": adf_p,
        "TestContractionRate": contraction_rate,
        "EquilibriumShiftSigma": equilibrium_shift,
        "DispersionRatio": dispersion_ratio,
        "TestLatestAbsZ": abs(float(test_z[-1]))
    }

